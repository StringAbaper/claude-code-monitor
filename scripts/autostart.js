#!/usr/bin/env node
// Starts the monitor when you log in to Windows.
//
//   node scripts/autostart.js install     register the scheduled task
//   node scripts/autostart.js uninstall   remove it
//   node scripts/autostart.js status      is it registered, is it running
//
// Two constraints shape this:
//
//   * The task runs in your interactive session, not as a background
//     service. Focus Window drives windows on your desktop, and a task in
//     session 0 cannot reach them.
//   * A console window would sit in your taskbar for the whole session, so
//     the task launches through a generated wscript shim that hides it.
//     Output goes to data/server.log instead, rewritten on each start.
//
// No administrator rights are needed: the task is registered for your own
// account with an interactive logon type, which asks for no password.

const { execFileSync } = require("child_process");
const fs = require("fs");
const path = require("path");
const os = require("os");

const ROOT = path.join(__dirname, "..");
const TASK_NAME = "Claude Code Monitor";
const LAUNCHER = path.join(ROOT, "data", "start-hidden.vbs");
const LOG = path.join(ROOT, "data", "server.log");
const PORT = process.env.PORT || 7888;

const command = process.argv[2] || "status";

if (process.platform !== "win32") {
  console.error(`Autostart is only implemented for Windows; this is ${process.platform}.`);
  console.error("On macOS use a launchd agent, on Linux a systemd --user unit, pointing at:");
  console.error(`  ${process.execPath} ${path.join(ROOT, "server.js")}`);
  process.exit(1);
}

// PowerShell single-quoted strings: the only escape is a doubled quote.
function psQuote(s) {
  return `'${String(s).replace(/'/g, "''")}'`;
}

function powershell(script) {
  return execFileSync(
    "powershell.exe",
    ["-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", "-Command", script],
    { encoding: "utf8", windowsHide: true }
  );
}

// The shim exists so no console window appears. It resolves nothing at run
// time — the node path and the working directory are baked in here, so a
// moved or reinstalled Node does not silently break startup. Re-run install
// after either.
function writeLauncher() {
  fs.mkdirSync(path.dirname(LAUNCHER), { recursive: true });
  const vbs = [
    "' Generated by scripts/autostart.js — re-run it after moving the repo",
    "' or changing your Node install. Starts the monitor with no window.",
    "' The `call` is load-bearing: when the command after /c starts with a",
    "' quote, cmd applies its own quote-stripping rule and the whole thing",
    "' fails silently — no process, no log, no error. `call` moves the quote",
    "' off the front. Do not remove it.",
    'Set sh = CreateObject("WScript.Shell")',
    `sh.CurrentDirectory = "${ROOT}"`,
    "' Waits (the True) rather than firing and forgetting: that keeps the",
    "' task alive for as long as the server runs, so Task Scheduler can see",
    "' it crash and restart it. Firing and forgetting would report success",
    "' the instant the server started and never look again.",
    `WScript.Quit sh.Run("cmd /c call ""${process.execPath}"" server.js > ""${LOG}"" 2>&1", 0, True)`,
    "",
  ].join("\r\n");
  fs.writeFileSync(LAUNCHER, vbs, "utf8");
}

function isRunning() {
  try {
    const out = powershell(
      `(Get-NetTCPConnection -LocalPort ${PORT} -State Listen -ErrorAction SilentlyContinue | Select-Object -First 1).OwningProcess`
    ).trim();
    return out ? Number(out) : null;
  } catch {
    return null;
  }
}

function taskExists() {
  try {
    const out = powershell(
      `if (Get-ScheduledTask -TaskName ${psQuote(TASK_NAME)} -ErrorAction SilentlyContinue) { 'yes' } else { 'no' }`
    ).trim();
    return out === "yes";
  } catch {
    return false;
  }
}

const WATCHDOG_MINUTES = 5;

function install() {
  writeLauncher();
  const user = `${os.userInfo().username}`;
  // Two triggers:
  //
  //   logon    starts it when you sit down at the machine
  //   repeat   every few minutes, as a watchdog
  //
  // The watchdog costs nothing while the server is up: MultipleInstances
  // IgnoreNew makes a repeat a no-op when the task is already running, and
  // the task runs for as long as the server does. When the server has died,
  // the next repeat brings it back.
  //
  // This replaces RestartOnFailure, which reads as if it would do the same
  // and does not: the task exiting with a failure code left it stopped for
  // good (measured — nothing restarted in over two minutes).
  //
  // ExecutionTimeLimit zero: a scheduled task is killed after three days by
  // default, which would quietly stop the monitor mid-week.
  const script = [
    `$action = New-ScheduledTaskAction -Execute 'wscript.exe' -Argument ${psQuote(`"${LAUNCHER}"`)} -WorkingDirectory ${psQuote(ROOT)}`,
    `$logon = New-ScheduledTaskTrigger -AtLogOn -User ${psQuote(user)}`,
    `$logon.Delay = 'PT10S'`,
    `$watchdog = New-ScheduledTaskTrigger -Once -At (Get-Date) -RepetitionInterval (New-TimeSpan -Minutes ${WATCHDOG_MINUTES}) -RepetitionDuration (New-TimeSpan -Days 3650)`,
    `$principal = New-ScheduledTaskPrincipal -UserId ${psQuote(user)} -LogonType Interactive -RunLevel Limited`,
    `$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -MultipleInstances IgnoreNew -ExecutionTimeLimit ([TimeSpan]::Zero)`,
    `Register-ScheduledTask -TaskName ${psQuote(TASK_NAME)} -Action $action -Trigger @($logon, $watchdog) -Principal $principal -Settings $settings -Force | Out-Null`,
  ].join("; ");
  powershell(script);

  console.log(`Registered scheduled task: ${TASK_NAME}`);
  console.log(`  runs      ${process.execPath} server.js`);
  console.log(`  in        ${ROOT}`);
  console.log(`  at        logon of ${user}, after a 10s delay`);
  console.log(`  watchdog  re-checks every ${WATCHDOG_MINUTES} min, restarts it if it died`);
  console.log(`  logs to   ${LOG}  (rewritten on each start)`);
  console.log("");
  const pid = isRunning();
  if (pid) {
    console.log(`Port ${PORT} is already served by pid ${pid} — the task takes over at next logon.`);
    console.log(`To hand over now:  npm run autostart:restart`);
  } else {
    console.log("Starting it now...");
    powershell(`Start-ScheduledTask -TaskName ${psQuote(TASK_NAME)}`);
  }
}

function uninstall() {
  if (!taskExists()) {
    console.log(`No scheduled task named "${TASK_NAME}".`);
    return;
  }
  powershell(`Unregister-ScheduledTask -TaskName ${psQuote(TASK_NAME)} -Confirm:$false`);
  try { fs.unlinkSync(LAUNCHER); } catch {}
  console.log(`Removed scheduled task: ${TASK_NAME}`);
  const pid = isRunning();
  if (pid) console.log(`The running server (pid ${pid}) was left alone. Stop it yourself if you want it gone.`);
}

// Hand the port over to the task: stop whatever holds it, then start the
// task so the running server is the managed one.
function restart() {
  if (!taskExists()) {
    console.error(`No scheduled task named "${TASK_NAME}". Run: npm run autostart`);
    process.exit(1);
  }
  // Stop the task first — it owns the whole wscript → cmd → node tree, and
  // killing only the node would look like a crash and trigger a restart
  // that fights this one.
  powershell(`Stop-ScheduledTask -TaskName ${psQuote(TASK_NAME)} -ErrorAction SilentlyContinue`);
  const pid = isRunning();
  if (pid) {
    // Something outside the task still holds the port — a server started by
    // hand, most likely.
    powershell(`Stop-Process -Id ${pid} -Force`);
    console.log(`Stopped pid ${pid} (not started by the task).`);
  }
  powershell(`Start-ScheduledTask -TaskName ${psQuote(TASK_NAME)}`);
  console.log("Started via the scheduled task.");
}

function status() {
  const exists = taskExists();
  console.log(`Scheduled task : ${exists ? TASK_NAME : "not registered"}`);
  if (exists) {
    const info = powershell(
      `$t = Get-ScheduledTask -TaskName ${psQuote(TASK_NAME)}; $i = $t | Get-ScheduledTaskInfo; ` +
      `"state=$($t.State) lastRun=$($i.LastRunTime) lastResult=$($i.LastTaskResult)"`
    ).trim();
    console.log(`  ${info}`);
  }
  const pid = isRunning();
  console.log(`Port ${PORT}      : ${pid ? `served by pid ${pid}` : "nothing listening"}`);
  if (fs.existsSync(LOG)) {
    const lines = fs.readFileSync(LOG, "utf8").split(/\r?\n/).filter(Boolean);
    console.log(`Log            : ${LOG}`);
    for (const l of lines.slice(-6)) console.log(`  ${l}`);
  }
}

const commands = { install, uninstall, restart, status };
if (!commands[command]) {
  console.error(`Unknown command "${command}". Use: install | uninstall | restart | status`);
  process.exit(1);
}

try {
  commands[command]();
} catch (err) {
  console.error(`Failed: ${err.message}`);
  if (err.stderr) console.error(String(err.stderr).trim());
  process.exit(1);
}
